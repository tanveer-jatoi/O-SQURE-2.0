import PDFDocument from 'pdfkit';
import QRCode from 'qrcode';
import { env } from '../config/env.js';

/**
 * Streams a printable A4 Fee Voucher PDF with itemized charges, due date,
 * payment reference, and an embedded scannable QR code.
 */
export async function streamFeeVoucherPdf(res, { voucher, student }) {
  const qrBuffer = await QRCode.toBuffer(voucher.qrPayloadString, {
    width: 130,
    margin: 1,
  });

  const doc = new PDFDocument({ size: 'A4', margin: 45 });

  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader(
    'Content-Disposition',
    `attachment; filename="Voucher-${voucher.voucherNumber}.pdf"`
  );
  doc.pipe(res);

  // Header Banner
  doc.rect(45, 45, 505, 62).fill('#0F172A');
  doc.fillColor('#FFFFFF').font('Helvetica-Bold').fontSize(17).text(env.campus.name, 60, 58);
  doc
    .font('Helvetica')
    .fontSize(9)
    .fillColor('#CBD5E1')
    .text(`Official Fee Voucher  |  ${env.campus.phone}  |  ${env.campus.email}`, 60, 82);

  // Voucher Metadata Box
  let y = 125;
  doc.fillColor('#0F172A').font('Helvetica-Bold').fontSize(13).text('FEE VOUCHER', 45, y);
  doc
    .font('Helvetica-Bold')
    .fontSize(10)
    .fillColor(voucher.status === 'paid' ? '#059669' : '#DC2626')
    .text(`STATUS: ${voucher.status.toUpperCase()}`, 400, y, { width: 150, align: 'right' });

  y += 24;
  doc.font('Helvetica').fontSize(10).fillColor('#334155');
  doc.text(`Voucher No:     ${voucher.voucherNumber}`, 45, y);
  doc.text(`Issue Date:     ${new Date(voucher.issueDate).toLocaleDateString()}`, 330, y);
  y += 16;
  doc.text(`Billing Month:  ${voucher.billingMonth}`, 45, y);
  doc.text(`Due Date:       ${new Date(voucher.dueDate).toLocaleDateString()}`, 330, y);
  y += 16;
  doc.text(`Student Name:   ${student.fullName}`, 45, y);
  doc.text(`Student ID:     ${student.studentId}`, 330, y);
  y += 16;
  doc.text(`Batch / Course: ${voucher.batchId?.batchCode || 'Unassigned'}`, 45, y);
  doc.text(`Payment Ref:    ${voucher.paymentReference}`, 330, y);

  // Itemized Breakdown Table
  y += 32;
  doc.rect(45, y, 505, 22).fill('#1E293B');
  doc.fillColor('#FFFFFF').font('Helvetica-Bold').fontSize(9);
  doc.text('FEE DESCRIPTION', 55, y + 6);
  doc.text('AMOUNT (PKR)', 420, y + 6, { width: 120, align: 'right' });

  y += 24;
  const rows = [
    [voucher.description, voucher.baseAmount.toLocaleString()],
    ['Discount / Scholarship Concession', `- ${voucher.discountAmount.toLocaleString()}`],
    ['Late Payment Charges', voucher.lateCharges.toLocaleString()],
  ];

  doc.font('Helvetica').fontSize(10).fillColor('#1E293B');
  rows.forEach(([label, amt], idx) => {
    if (idx % 2 === 1) {
      doc.rect(45, y - 3, 505, 22).fill('#F8FAFC');
      doc.fillColor('#1E293B');
    }
    doc.text(label, 55, y + 2, { width: 350 });
    doc.text(amt, 420, y + 2, { width: 120, align: 'right' });
    y += 22;
  });

  // Total Payable Row
  doc.rect(45, y + 4, 505, 26).fill('#EEF2FF');
  doc.font('Helvetica-Bold').fontSize(11).fillColor('#312E81');
  doc.text('TOTAL PAYABLE AMOUNT', 55, y + 11);
  doc.text(`PKR ${voucher.totalPayable.toLocaleString()}`, 400, y + 11, {
    width: 140,
    align: 'right',
  });

  // Payment Instructions + Embedded QR Code
  y += 50;
  doc.rect(45, y, 505, 130).strokeColor('#CBD5E1').stroke();
  doc.image(qrBuffer, 58, y + 10, { width: 110, height: 110 });

  doc.font('Helvetica-Bold').fontSize(10).fillColor('#0F172A').text('PAYMENT INSTRUCTIONS', 185, y + 16);
  doc.font('Helvetica').fontSize(9).fillColor('#475569');
  doc.text(`1. Scan the QR code using your banking app (Raast) or Student Portal.`, 185, y + 34, { width: 345 });
  doc.text(`2. Or use Payment Reference: ${voucher.paymentReference} via 1Link / Online Banking.`, 185, y + 50, { width: 345 });
  doc.text(`3. Late payment charges apply automatically after the Due Date.`, 185, y + 66, { width: 345 });
  doc.text(`4. Official PDF Receipt is issued automatically upon transaction verification.`, 185, y + 82, { width: 345 });

  doc
    .fontSize(8)
    .fillColor('#64748B')
    .text(`Generated by O-Square 2.0 Educational ERP on ${new Date().toLocaleString()}`, 45, 760, {
      align: 'center',
      width: 505,
    });

  doc.end();
}

/**
 * Streams a printable A4 Verified Payment Receipt PDF.
 */
export async function streamPaymentReceiptPdf(res, { receipt, voucher, student }) {
  const qrPayload = `OSQ2-RECEIPT|${receipt.receiptNumber}|${receipt.transactionReference}|PKR ${receipt.amountPaid}`;
  const qrBuffer = await QRCode.toBuffer(qrPayload, { width: 110, margin: 1 });

  const doc = new PDFDocument({ size: 'A4', margin: 45 });

  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader(
    'Content-Disposition',
    `attachment; filename="Receipt-${receipt.receiptNumber}.pdf"`
  );
  doc.pipe(res);

  // Header
  doc.rect(45, 45, 505, 62).fill('#065F46');
  doc.fillColor('#FFFFFF').font('Helvetica-Bold').fontSize(17).text(env.campus.name, 60, 58);
  doc
    .font('Helvetica')
    .fontSize(9)
    .fillColor('#D1FAE5')
    .text(`Official Payment Receipt  |  ${env.campus.phone}  |  ${env.campus.email}`, 60, 82);

  let y = 128;
  doc.fillColor('#0F172A').font('Helvetica-Bold').fontSize(13).text('PAYMENT RECEIPT', 45, y);
  doc.fillColor('#059669').fontSize(10).text('VERIFIED & SETTLED', 400, y, { width: 150, align: 'right' });

  y += 28;
  const details = [
    ['Receipt Number:', receipt.receiptNumber],
    ['Payment Date:', new Date(receipt.issuedAt).toLocaleString()],
    ['Student Name:', student.fullName],
    ['Student ID:', student.studentId],
    ['Voucher Number:', voucher?.voucherNumber || '—'],
    ['Billing Month:', voucher?.billingMonth || '—'],
    ['Payment Method:', receipt.paymentMethod.replace('_', ' ').toUpperCase()],
    ['Transaction Reference:', receipt.transactionReference],
  ];

  details.forEach(([k, v]) => {
    doc.font('Helvetica-Bold').fontSize(10).fillColor('#334155').text(k, 45, y, { width: 160 });
    doc.font('Helvetica').fillColor('#0F172A').text(String(v), 210, y, { width: 320 });
    y += 20;
  });

  y += 10;
  doc.rect(45, y, 505, 32).fill('#ECFDF5');
  doc.font('Helvetica-Bold').fontSize(12).fillColor('#065F46');
  doc.text('AMOUNT PAID', 60, y + 9);
  doc.text(`PKR ${receipt.amountPaid.toLocaleString()}`, 390, y + 9, { width: 145, align: 'right' });

  y += 50;
  doc.image(qrBuffer, 45, y, { width: 95, height: 95 });
  doc
    .font('Helvetica')
    .fontSize(9)
    .fillColor('#475569')
    .text(
      'This is a computer-generated verified receipt from O-Square 2.0 ERP. No manual signature is required.',
      155,
      y + 25,
      { width: 380 }
    );

  doc.end();
}
