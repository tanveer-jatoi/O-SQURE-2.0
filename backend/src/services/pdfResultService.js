import PDFDocument from 'pdfkit';
import { env } from '../config/env.js';

/**
 * Streams a printable A4 Result Card PDF for a student's published examination results.
 */
export function streamResultCardPdf(res, { student, examination, results }) {
  const doc = new PDFDocument({ size: 'A4', margin: 45 });

  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader(
    'Content-Disposition',
    `attachment; filename="Result-${student.studentId}-${examination.examCode}.pdf"`
  );

  doc.pipe(res);

  // Header
  doc.fontSize(18).font('Helvetica-Bold').fillColor('#0F172A').text(env.campus.name);
  doc
    .fontSize(10)
    .font('Helvetica')
    .fillColor('#475569')
    .text(`Official Academic Result Card  |  ${env.campus.phone}  |  ${env.campus.email}`);
  doc.moveDown(0.8);
  doc.moveTo(45, doc.y).lineTo(550, doc.y).strokeColor('#CBD5E1').stroke();
  doc.moveDown(1);

  // Exam & Student Block
  doc.fontSize(13).font('Helvetica-Bold').fillColor('#1E293B').text(examination.title);
  doc
    .fontSize(10)
    .font('Helvetica')
    .fillColor('#334155')
    .text(`Exam Code: ${examination.examCode}   |   Term: ${examination.term.toUpperCase()}`);
  doc.moveDown(0.7);

  doc.text(`Student Name: ${student.fullName}`);
  doc.text(`Student ID:   ${student.studentId}`);
  doc.text(`Father Name:  ${student.fatherName}`);
  doc.moveDown(1.2);

  // Table Header
  const startX = 45;
  let y = doc.y;
  doc.rect(startX, y, 505, 22).fill('#0F172A');
  doc.fillColor('#FFFFFF').font('Helvetica-Bold').fontSize(9);
  doc.text('SUBJECT', startX + 8, y + 6, { width: 200 });
  doc.text('MAX MARKS', startX + 215, y + 6, { width: 70, align: 'right' });
  doc.text('OBTAINED', startX + 295, y + 6, { width: 70, align: 'right' });
  doc.text('%', startX + 375, y + 6, { width: 50, align: 'right' });
  doc.text('GRADE', startX + 435, y + 6, { width: 65, align: 'right' });

  y += 24;
  let totalMax = 0;
  let totalGot = 0;

  doc.font('Helvetica').fontSize(9).fillColor('#1E293B');
  results.forEach((r, idx) => {
    const maxM = r.examSubjectId?.totalMarks || 100;
    totalMax += maxM;
    totalGot += r.marksObtained;

    if (idx % 2 === 1) {
      doc.rect(startX, y - 2, 505, 20).fill('#F8FAFC');
      doc.fillColor('#1E293B');
    }

    const subjName = r.examSubjectId?.subjectId?.title || 'Subject';
    doc.text(subjName, startX + 8, y + 3, { width: 200 });
    doc.text(String(maxM), startX + 215, y + 3, { width: 70, align: 'right' });
    doc.text(r.isAbsent ? 'ABS' : String(r.marksObtained), startX + 295, y + 3, {
      width: 70,
      align: 'right',
    });
    doc.text(`${r.percentage}%`, startX + 375, y + 3, { width: 50, align: 'right' });
    doc.text(r.grade, startX + 435, y + 3, { width: 65, align: 'right' });
    y += 20;
  });

  doc.moveTo(startX, y + 4).lineTo(550, y + 4).strokeColor('#CBD5E1').stroke();
  const overallPct = totalMax > 0 ? Math.round((totalGot / totalMax) * 10000) / 100 : 0;

  doc
    .font('Helvetica-Bold')
    .fontSize(10)
    .fillColor('#0F172A')
    .text(`Aggregate Score: ${totalGot} / ${totalMax} (${overallPct}%)`, startX, y + 14);

  doc
    .fontSize(8)
    .font('Helvetica')
    .fillColor('#64748B')
    .text(`Generated by O-Square 2.0 ERP on ${new Date().toLocaleString()}`, 45, 760, {
      align: 'center',
      width: 505,
    });

  doc.end();
}
